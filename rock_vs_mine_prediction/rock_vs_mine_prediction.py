import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression
from sklearn.metrics import accuracy_score


df = pd.read_csv('/content/sonar_dataset.csv', header= None)

from sklearn.preprocessing import LabelEncoder

label_encoder = LabelEncoder()
df[60] = label_encoder.fit_transform(df[60])

"""Seperating the label and data"""

X = df.drop(columns=60 , axis = 1)
Y = df[60]

"""Now training and testing the data"""

X_train, X_test, Y_train, Y_test = train_test_split(X, Y, test_size = 0.1, stratify=Y,  random_state=1)

"""Model Training -----> Logistic Regression

"""

model = LinearRegression()
model.fit(X_train, Y_train)

"""Model Evalution"""

X_train_prediction_continuous = model.predict(X_train)
# Convert continuous predictions to binary (0 or 1) using a threshold of 0.5
X_train_prediction_binary = (X_train_prediction_continuous >= 0.5).astype(int)
traind_data_accuracy = accuracy_score(X_train_prediction_binary, Y_train)

print(traind_data_accuracy)

X_test_prediction_continuous = model.predict(X_test)
# Convert continuous predictions to binary (0 or 1) using a threshold of 0.5
X_test_prediction_binary = (X_test_prediction_continuous >= 0.5).astype(int)
test_data_accuracy = accuracy_score(X_test_prediction_binary, Y_test)

print(test_data_accuracy)